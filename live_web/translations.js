// Get current language from localStorage or default to 'en'
function getCurrentLanguage() {
    return localStorage.getItem('language') || 'en';
}

// Set language and update UI
function setLanguage(lang) {
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;
    // We'll reload the page instead of just updating content
    // This ensures all dynamic content is properly refreshed
    // The page will reload only if we're not already in the process of setting up
    if (window.languageInitialized) {
        window.location.reload();
    } else {
        updateContent();
    }
}

// Update all content with translations
function updateContent() {
    const lang = getCurrentLanguage();

    // Update all elements with translate class
    document.querySelectorAll('.translate').forEach(element => {
        const key = element.getAttribute('data-key');
        if (key && translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Update form placeholders
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(element => {
        const placeholder = element.getAttribute('placeholder');
        if (placeholder && translations[lang] && translations[lang][placeholder.toLowerCase()]) {
            element.setAttribute('placeholder', translations[lang][placeholder.toLowerCase()]);
        }
    });

    // Update language display
    document.getElementById('current-lang').textContent = lang.toUpperCase();
    if (document.getElementById('mobile-current-lang')) {
        document.getElementById('mobile-current-lang').textContent = lang.toUpperCase();
    }
}

// Initialize translations when DOM is loaded
document.addEventListener('DOMContentLoaded', function() {
    // Set flag to false initially
    window.languageInitialized = false;

    // Set up language switchers
    document.querySelectorAll('.dropdown-content a').forEach(link => {
        link.addEventListener('click', function(e) {
            e.preventDefault();
            const lang = this.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    // Initial content update
    updateContent();

    // Set flag to true after initialization
    setTimeout(() => {
        window.languageInitialized = true;
    }, 500);
});
